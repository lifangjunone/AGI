import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";

const require = createRequire(import.meta.url);
const { dictionary } = require("cmu-pronouncing-dictionary");

const phonemes = {
  AA: "ɑ", AE: "æ", AH: "ʌ", AO: "ɔ", AW: "aʊ", AY: "aɪ",
  B: "b", CH: "tʃ", D: "d", DH: "ð", EH: "ɛ", ER: "ɝ",
  EY: "eɪ", F: "f", G: "ɡ", HH: "h", IH: "ɪ", IY: "i",
  JH: "dʒ", K: "k", L: "l", M: "m", N: "n", NG: "ŋ",
  OW: "oʊ", OY: "ɔɪ", P: "p", R: "r", S: "s", SH: "ʃ",
  T: "t", TH: "θ", UH: "ʊ", UW: "u", V: "v", W: "w",
  Y: "j", Z: "z", ZH: "ʒ"
};

function toIpa(pronunciation) {
  const rendered = [];
  let previousVowelIndex = -1;
  for (const token of pronunciation.split(" ")) {
    const match = token.match(/^([A-Z]+)([012])?$/);
    if (!match) continue;
    const [, phoneme, stress] = match;
    let symbol = phonemes[phoneme] ?? "";
    if (phoneme === "AH" && stress === "0") symbol = "ə";
    if (phoneme === "ER" && stress === "0") symbol = "ɚ";
    if (stress === "1" || stress === "2") {
      rendered.splice(
        previousVowelIndex < 0 ? 0 : previousVowelIndex + 1,
        0,
        stress === "1" ? "ˈ" : "ˌ"
      );
    }
    rendered.push(symbol);
    if (stress !== undefined) previousVowelIndex = rendered.length - 1;
  }
  return rendered.join("");
}

const source = await readFile(
  new URL("../src/supplemental-lexicon.ts", import.meta.url),
  "utf8"
);
const block = source.match(/const glossarySource = `([\s\S]*?)`;/)?.[1] ?? "";
const words = block
  .trim()
  .split("\n")
  .map((line) => line.slice(0, line.indexOf("|")));

const pronunciations = Object.fromEntries(
  words.map((word) => {
    const pronunciation =
      dictionary[word] ??
      dictionary[word.replace(/s$/, "")] ??
      dictionary[word.replace(/ed$/, "")] ??
      dictionary[word.replace(/ing$/, "")];
    return [word, pronunciation ? `/${toIpa(pronunciation)}/` : ""];
  })
);

const output = `// Generated by scripts/generate-scene-ipa.mjs from CMUdict.\nexport const supplementalIpa: Record<string, string> = ${JSON.stringify(
  pronunciations,
  null,
  2
)};\n`;

await writeFile(
  new URL("../src/supplemental-ipa.ts", import.meta.url),
  output,
  "utf8"
);
